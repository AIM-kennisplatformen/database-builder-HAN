def _workbook_bytes(populate: Callable[[Workbook], None]) -> bytes:
    workbook = Workbook()
    populate(workbook)
    output = BytesIO()
    workbook.save(output)
    return output.getvalue()


def _workbook_with_wrong_header() -> bytes:
    def populate(workbook: Workbook) -> None:
        sheet = workbook.active
        assert sheet is not None
        sheet.append(["wrong header"])

    return _workbook_bytes(populate)


def test_ib_parser_finds_headers_on_later_sheet_and_reports_bad_rows() -> None:
    def populate(workbook: Workbook) -> None:
        first_sheet = workbook.active
        assert first_sheet is not None
        first_sheet.append(["unrelated sheet"])
        sheet = workbook.create_sheet("Import")
        sheet.append(["Export generated by HAN"])
        sheet.append(list(IB_HEADERS))
        sheet.append([" P-1 ", " Project ", " Ada ", 8, 7.5, 6, 3, 2, " CC "])
        sheet.append(["P-2", "Project", "Bob", True, 7, 6, 3, 2, "CC"])
        sheet.append([None] * len(IB_HEADERS))

    parser = UbwfrisIbExcelParser()

    async def collect():
        return [
            row
            async for row in parser.stream_ubwfris_rows(
                UbwfrisWorkbook[IbRow](_workbook_bytes(populate))
            )
        ]

    parsed = asyncio.run(collect())

    assert [(row.row_number, row.total_rows) for row in parsed] == [(3, 2), (4, 2)]
    assert parsed[0].row is not None
    assert parsed[0].row.project_id == "P-1"
    assert parsed[0].row.project_name == "Project"
    assert parsed[0].row.employee_name == "Ada"
    assert parsed[0].row.budgeted_hours == Decimal(8)
    assert parsed[0].row.projected_hours == Decimal("7.5")
    assert parsed[0].row.period == 3
    assert parsed[0].row.cost_center == "CC"
    assert parsed[1].row is None


def test_rha_parser_uses_second_duplicate_employment_cost_center_and_excel_date() -> (
    None
):
    headers = [*RHA_HEADERS, "Aanstellingskostenplaats"]
    row = [
        "1001",
        "Ada Lovelace",
        "Grace Hopper",
        "P-1",
        "Active",
        "Project One",
        "SP-1",
        "Active",
        "Subproject One",
        "CC-1",
        45000,
        8.5,
        "Research",
        80,
        "Department",
        "Academy",
        "Department Name",
        "Old employment center",
        "Current employment center",
    ]

    def populate(workbook: Workbook) -> None:
        sheet = workbook.active
        assert sheet is not None
        sheet.append(list(headers))
        sheet.append(row)

    parser = UbwfrisRhaExcelParser()

    async def collect():
        return [
            item
            async for item in parser.stream_ubwfris_rows(
                UbwfrisWorkbook[RhaRow](_workbook_bytes(populate))
            )
        ]

    parsed = asyncio.run(collect())

    assert len(parsed) == 1
    assert parsed[0].row is not None
    assert parsed[0].row.employee_number == "1001"
    assert parsed[0].row.registration_date == date(2023, 3, 15)
    assert parsed[0].row.hours == Decimal("8.5")
    assert parsed[0].row.parttime_percentage == 80
    assert parsed[0].row.employment_cost_center == "Current employment center"


@pytest.mark.parametrize("data", [b"not an excel file", _workbook_with_wrong_header()])
def test_ib_parser_rejects_unreadable_or_unrecognized_workbooks(data: bytes) -> None:
    async def collect() -> None:
        async for _row in UbwfrisIbExcelParser().stream_ubwfris_rows(
            UbwfrisWorkbook[IbRow](data)
        ):
            pass

    with pytest.raises(InvalidWorkbook):
        asyncio.run(collect())


